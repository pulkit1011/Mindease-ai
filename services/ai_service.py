"""AI chat integration with a safe, clearly labelled offline fallback.

Order of operations for every user message (see get_chat_reply):
  1. safety_service checks the message FIRST. Flagged messages get a fixed response and
     are never sent to the model.
  2. If an API key is configured, the message plus recent chat turns are sent to the model.
     Mood records and personal notes are NEVER sent.
  3. If there is no key or the call fails, a clearly labelled fallback reply is returned.
"""
import logging
from dataclasses import dataclass
from typing import Callable, Optional

import config
from services import safety_service

logger = logging.getLogger(__name__)

FALLBACK_LABEL = "Offline fallback reply (not generated by an AI model)"
MAX_HISTORY_TURNS = 10
MAX_MESSAGE_CHARS = 2000

SYSTEM_PROMPT = (
    "You are MindEase, a supportive wellness chat assistant for young people and college students. "
    "You are an AI program, not a human, therapist or doctor, and you must never claim otherwise. "
    "Use warm, nonjudgmental, plain language and keep replies short (under about 150 words). "
    "Help with everyday stress, study pressure, motivation, routines, relaxation and journaling prompts. "
    "Do not diagnose, name conditions the user may have, give medication advice or change treatment plans. "
    "Do not promise confidentiality or claim to monitor, alert or contact anyone. "
    "Do not encourage dependence on this chat; encourage real-world support from friends, family, "
    "counsellors or qualified professionals when problems are persistent or severe. "
    "If the user mentions self-harm, suicide, abuse or immediate danger, gently urge them to contact local "
    "emergency services or a trusted person. Offer small, practical next steps and ask at most one question."
)

_ERROR_TEXT = {
    "no_key": "No AI API key is configured.",
    "sdk_missing": "The AI software package is not installed.",
    "rate_limited": "The AI service is busy right now (rate limit reached).",
    "timeout": "The AI service took too long to respond.",
    "connection": "Could not connect to the AI service.",
    "auth": "The AI service rejected the configured credentials.",
    "invalid_response": "The AI service returned an unusable reply.",
    "unknown": "The AI service had an unexpected problem.",
}


@dataclass
class ModelResult:
    ok: bool
    text: str = ""
    error_code: Optional[str] = None

    @property
    def error_message(self) -> str:
        return _ERROR_TEXT.get(self.error_code, "") if self.error_code else ""


@dataclass
class ChatReply:
    text: str
    source: str            # "safety", "boundary", "ai" or "fallback"
    note: str = ""         # why a fallback was used (never contains secrets)


def redact(text: str, secret: str) -> str:
    return text.replace(secret, "[redacted]") if secret and secret in text else text


def classify_error(exc: Exception) -> str:
    """Map any exception to a short code without exposing its message."""
    name = type(exc).__name__.lower()
    status = getattr(exc, "status_code", None)
    if "ratelimit" in name or status == 429:
        return "rate_limited"
    if "timeout" in name:
        return "timeout"
    if "connection" in name:
        return "connection"
    if "authentication" in name or "permission" in name or status in (401, 403):
        return "auth"
    return "unknown"


def _default_client_factory(api_key: str, timeout: float):
    import anthropic  # imported lazily so the app runs even if the package is missing
    return anthropic.Anthropic(api_key=api_key, timeout=timeout, max_retries=1)


class AIService:
    def __init__(self, api_key: str = None, model: str = None, timeout: float = None,
                 max_tokens: int = None, client_factory: Callable = None):
        s = config.get_ai_settings()
        self.api_key = s["api_key"] if api_key is None else api_key.strip()
        self.model = model or s["model"]
        self.timeout = s["timeout"] if timeout is None else timeout
        self.max_tokens = max_tokens or s["max_tokens"]
        self._factory = client_factory or _default_client_factory

    @property
    def is_configured(self) -> bool:
        return self.api_key not in config.PLACEHOLDER_KEYS

    def generate(self, messages: list) -> ModelResult:
        if not self.is_configured:
            return ModelResult(False, error_code="no_key")
        try:
            client = self._factory(self.api_key, self.timeout)
        except ImportError:
            return ModelResult(False, error_code="sdk_missing")
        except Exception as exc:
            logger.warning("AI client setup failed: %s", type(exc).__name__)
            return ModelResult(False, error_code=classify_error(exc))
        try:
            response = client.messages.create(model=self.model, max_tokens=self.max_tokens,
                                              system=SYSTEM_PROMPT, messages=messages)
            blocks = getattr(response, "content", None) or []
            text = "".join(getattr(b, "text", "") for b in blocks if getattr(b, "type", "") == "text").strip()
        except Exception as exc:  # log the class name only: messages could echo request data
            logger.warning("AI request failed: %s", type(exc).__name__)
            return ModelResult(False, error_code=classify_error(exc))
        if not text:
            return ModelResult(False, error_code="invalid_response")
        return ModelResult(True, text=redact(text, self.api_key))


def prepare_messages(history: list, user_message: str) -> list:
    """Keep only role/content of the last few turns, trimmed. Nothing else is sent."""
    msgs = [{"role": m["role"], "content": str(m["content"])[:MAX_MESSAGE_CHARS]}
            for m in history[-MAX_HISTORY_TURNS:] if m.get("role") in ("user", "assistant") and m.get("content")]
    msgs.append({"role": "user", "content": user_message[:MAX_MESSAGE_CHARS]})
    while msgs and msgs[0]["role"] != "user":   # the API expects the first turn to be from the user
        msgs.pop(0)
    return msgs


_FALLBACK_TOPICS = [
    (("exam", "test", "viva", "result", "marks"),
     "Exam pressure is really common. Try breaking revision into small blocks (for example 25 minutes of focus, "
     "then a 5-minute break), start with the topic that feels easiest to build momentum, and keep a regular "
     "sleep time. What is one small thing you could study today?"),
    (("procrastinat", "motivation", "unmotivated", "can't start", "cant start", "lazy"),
     "Getting started is often the hardest part. Try the 2-minute rule: commit to just two minutes of the task. "
     "Writing the very first tiny step down can also make it feel less heavy."),
    (("sleep", "tired", "insomnia", "exhausted"),
     "Rest matters. A steady bedtime, dimmer lights and less screen time before sleep can help. If sleep "
     "problems last for weeks, a doctor or counsellor can help."),
    (("worry", "anxious", "anxiety", "nervous", "overthink", "stress"),
     "That sounds stressful. One thing to try is slow breathing: in for 4, hold for 4, out for 6, a few "
     "times. Writing your worries down and marking which ones you can act on may also help. "
     "The Self-care page has guided exercises."),
    (("lonely", "alone", "friends", "homesick"),
     "Feeling lonely can be hard, especially away from home. Even a short message to one person you trust "
     "can help, and many campuses have clubs or counselling cells where it is easy to meet people."),
]
_FALLBACK_DEFAULT = ("Thanks for sharing that. I'm running without an AI model right now, so my replies are limited. "
                     "You could try a check-in, a breathing exercise on the Self-care page, or a journaling "
                     "prompt. If something feels heavy or lasts a long time, talking to a trusted person or "
                     "a counsellor can help.")


def fallback_reply(user_message: str) -> str:
    low = (user_message or "").lower()
    for keys, text in _FALLBACK_TOPICS:
        if any(k in low for k in keys):
            return text
    return _FALLBACK_DEFAULT


def get_chat_reply(user_message: str, history: list = None, service: AIService = None,
                   resources: list = None) -> ChatReply:
    """Single entry point used by the chat page."""
    history = history or []
    result = safety_service.assess_message(user_message)
    if result.needs_special_handling:   # safety first; the model is never called for these
        text = safety_service.build_response(result, resources)
        return ChatReply(text, "boundary" if result.level == "boundary" else "safety")

    service = service or AIService()
    outcome = service.generate(prepare_messages(history, user_message))
    if outcome.ok:
        return ChatReply(outcome.text, "ai")
    return ChatReply(fallback_reply(user_message), "fallback", note=outcome.error_message)
